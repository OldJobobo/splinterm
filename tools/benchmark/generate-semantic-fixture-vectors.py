#!/usr/bin/env python3
"""Generate dependency-free Rust vectors from canonical Foot semantic fixtures."""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "fixtures/terminal/v1"
OUTPUT = ROOT / "crates/splinterm-terminal/tests/data/oracle_fixture_vectors.rs"
PINNED_FOOT = "3c5b584b0eafa772eb4376fb6eaf6643399e190e"
BOOLEAN_ATTRIBUTES = (
    "bold",
    "dim",
    "italic",
    "underline",
    "blink",
    "reverse",
    "conceal",
    "strikethrough",
)


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def rust_bytes(value: bytes) -> str:
    escaped = "".join(
        chr(byte) if 0x20 <= byte <= 0x7E and byte not in (ord('"'), ord('\\')) else f"\\x{byte:02x}"
        for byte in value
    )
    return f'b"{escaped}"'


def color(value: dict[str, Any] | None) -> str:
    if value is None:
        return "None"
    source = {
        "default": "Default",
        "base16": "Base16",
        "base256": "Base256",
        "rgb": "Rgb",
    }[value["source"]]
    return f"Some(ExpectedColor {{ source: ExpectedColorSource::{source}, value: {value['value']} }})"


def attributes(value: dict[str, Any]) -> str:
    fields = [f"{name}: {str(value.get(name, False)).lower()}" for name in BOOLEAN_ATTRIBUTES]
    fields.extend((f"foreground: {color(value.get('foreground'))}", f"background: {color(value.get('background'))}"))
    return "ExpectedAttributes { " + ", ".join(fields) + " }"


def generate() -> str:
    documents = []
    for path in sorted(FIXTURES.glob("*.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        if document["reference"]["commit"] != PINNED_FOOT:
            raise ValueError(f"{path}: Foot commit drift")
        if document["reference"]["verification"] != "oracle_verified":
            raise ValueError(f"{path}: fixture is not oracle verified")
        if document["intentional_divergences"]:
            raise ValueError(f"{path}: fixture has an intentional divergence")
        documents.append(document)
    if len(documents) != 5:
        raise ValueError(f"expected 5 semantic fixtures, found {len(documents)}")

    lines = [
        "// @generated by tools/benchmark/generate-semantic-fixture-vectors.py; do not edit.",
        "#[rustfmt::skip]",
        "const FIXTURES: &[Fixture] = &[",
    ]
    for document in documents:
        expected = document["expected"]
        lines.extend(
            [
                "    Fixture {",
                f"        id: {rust_string(document['id'])},",
                f"        foot_commit: {rust_string(document['reference']['commit'])},",
                f"        verification: {rust_string(document['reference']['verification'])},",
                f"        columns: {document['initial']['columns']},",
                f"        rows: {document['initial']['rows']},",
                f"        input: {rust_bytes(bytes.fromhex(document['input_hex']))},",
                "        cursor: ExpectedCursor { "
                f"column: {expected['cursor']['column']}, row: {expected['cursor']['row']}, "
                f"deferred_wrap: {str(expected['cursor']['last_column_flag']).lower()}"
                " },",
                "        expected_rows: &[",
            ]
        )
        for row in expected["rows"]:
            lines.append(
                "            ExpectedRow { "
                f"text: {rust_string(row['text'])}, linebreak: {str(row['linebreak']).lower()}"
                " },"
            )
        lines.append("        ],")
        lines.append("        attribute_runs: &[")
        for run in expected["attribute_runs"]:
            lines.append(
                "            ExpectedAttributeRun { "
                f"row: {run['row']}, start: {run['start']}, end: {run['end']}, "
                f"attributes: {attributes(run['attributes'])}"
                " },"
            )
        lines.extend(
            [
                "        ],",
                f"        expected_event_count: {len(expected['events'])},",
                "    },",
            ]
        )
    lines.extend(["];", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = generate()
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        print(f"Fixture vector generation failed: {error}", file=sys.stderr)
        return 1
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8")
        except OSError as error:
            print(f"Fixture vectors missing: {error}", file=sys.stderr)
            return 1
        if current != generated:
            print("Semantic fixture vectors are stale; rerun the generator.", file=sys.stderr)
            return 1
        print("Semantic fixture vectors match 5 canonical Foot fixtures.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
